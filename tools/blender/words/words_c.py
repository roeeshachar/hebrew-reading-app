    me = bpy.data.meshes.new('hd'); o = bpy.data.objects.new('hd', me); bpy.context.scene.collection.objects.link(o)
    n = 48; bm = bmesh.new(); f, k = [], []
    for i in range(n + 1):
        a = math.pi + math.pi * i / n; x, z = r * math.cos(a), r * math.sin(a)
        f.append(bm.verts.new((x, y0, z))); k.append(bm.verts.new((x, y0 + depth, z)))
    bm.faces.new(f); bm.faces.new(list(reversed(k)))
    for i in range(n): bm.faces.new((f[i], f[i + 1], k[i + 1], k[i]))
    bm.faces.new((f[-1], f[0], k[0], k[-1]))
    bm.normal_update(); bm.to_mesh(me); bm.free(); o.data.materials.append(M(color, rough)); smooth(o)
    b = o.modifiers.new('b', 'BEVEL'); b.width = 0.07; b.segments = 3; b.limit_method = 'ANGLE'
